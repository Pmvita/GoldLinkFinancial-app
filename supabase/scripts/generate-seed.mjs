#!/usr/bin/env node
/**
 * Regenerate supabase/seed.sql from db/*.json.
 *
 * Usage:   pnpm db:regenerate-seed
 * Output:  written to stdout — wire that into the seed.sql file via the
 *          npm script.
 *
 * Why a script and not hand-written SQL? db/*.json is the canonical source
 * for demo data. If it ever changes (new users, more transactions) we want
 * a one-liner to keep seed.sql in sync.
 *
 * ID strategy: legacy ids ("USR-001", "ACC-001-CHK", ...) are mapped to
 * deterministic uuid v5 values keyed by a constant namespace. That keeps
 * foreign keys consistent across re-runs and across local checkouts.
 */

import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const REPO_ROOT = join(__dirname, '..', '..');
const DB_DIR = join(REPO_ROOT, 'db');

const NAMESPACE = 'goldlink-bank:';

/** Map a legacy id (e.g. "USR-001") to a deterministic uuid v5. */
function legacyToUuid(legacyId) {
  const hash = createHash('sha1')
    .update(NAMESPACE + legacyId)
    .digest('hex');
  // Force the version (nybble 12) to 5 and the variant (nybble 16) to 8.
  return [
    hash.slice(0, 8),
    hash.slice(8, 12),
    '5' + hash.slice(13, 16),
    '8' + hash.slice(17, 20),
    hash.slice(20, 32),
  ].join('-');
}

function readJson(filename) {
  return JSON.parse(readFileSync(join(DB_DIR, filename), 'utf8'));
}

function sqlString(value) {
  if (value === null || value === undefined) return 'null';
  return `'${String(value).replaceAll("'", "''")}'`;
}

function sqlNumber(value) {
  if (value === null || value === undefined) return 'null';
  return String(value);
}

function sqlInteger(value) {
  if (value === null || value === undefined) return 'null';
  return String(Math.trunc(Number(value)));
}

function sqlBool(value) {
  return value ? 'true' : 'false';
}

function sqlJson(value) {
  if (value === null || value === undefined) return 'null';
  return `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
}

function sqlTextArray(values) {
  if (!values || values.length === 0) return `'{}'::text[]`;
  const inner = values
    .map((v) => `"${String(v).replaceAll('"', '\\"')}"`)
    .join(',');
  return `'{${inner}}'::text[]`;
}

function sqlDate(value) {
  if (!value) return 'null';
  return `'${value}'::date`;
}

function sqlTimestamp(value) {
  if (!value) return 'null';
  return `'${value}'::timestamptz`;
}

function uuid(legacyId) {
  return `'${legacyToUuid(legacyId)}'::uuid`;
}

// ---------------------------------------------------------------------------
// Load data
// ---------------------------------------------------------------------------

const usersData = readJson('users.json');
const accountsData = readJson('accounts.json');
const transactionsData = readJson('transactions.json');
const cardsData = readJson('cards.json');
const payeesData = readJson('payees.json');
const budgetsData = readJson('budgets.json');

// ---------------------------------------------------------------------------
// Emit
// ---------------------------------------------------------------------------

const out = [];
out.push(
  '-- GoldLink Bank — seed data.',
  '--',
  '-- Generated by `pnpm db:regenerate-seed` from db/*.json.',
  '-- Do not edit by hand — re-run the script instead.',
  '--',
  '-- Legacy ids (USR-001, ACC-001-CHK, ...) are mapped to deterministic',
  '-- uuid v5 values via sha1(NAMESPACE + legacy_id). The mapping lives in',
  '-- supabase/scripts/generate-seed.mjs and is stable across re-runs.',
  '',
  'begin;',
  ''
);

// Tiers — read straight off the users.json "tiers" object.
out.push('-- Tiers');
out.push(
  'insert into public.tiers (tier, name, min_balance, max_balance, benefits, fees) values'
);
const tierRows = Object.entries(usersData.tiers).map(
  ([tier, info]) =>
    `  (${sqlString(tier)}, ${sqlString(info.name)}, ${sqlNumber(info.minBalance)}, ${sqlNumber(info.maxBalance)}, ${sqlTextArray(info.benefits)}, ${sqlJson(info.fees)})`
);
out.push(tierRows.join(',\n') + '\non conflict (tier) do nothing;\n');

// Users
out.push('-- Users');
out.push(
  'insert into public.users (id, username, password, first_name, last_name, full_name, email, phone, tier, tier_name, relationship_manager, relationship_manager_phone, member_since, date_of_birth, address, preferences, last_login) values'
);
const userRows = usersData.users.map(
  (u) =>
    `  (${uuid(u.id)}, ${sqlString(u.username)}, ${sqlString(u.password)}, ${sqlString(u.firstName)}, ${sqlString(u.lastName)}, ${sqlString(u.fullName)}, ${sqlString(u.email)}, ${sqlString(u.phone)}, ${sqlString(u.tier)}, ${sqlString(u.tierName)}, ${sqlString(u.relationshipManager)}, ${sqlString(u.relationshipManagerPhone)}, ${sqlDate(u.memberSince)}, ${sqlDate(u.dateOfBirth)}, ${sqlJson(u.address)}, ${sqlJson(u.preferences)}, ${sqlTimestamp(u.lastLogin)})`
);
out.push(userRows.join(',\n') + '\non conflict (id) do nothing;\n');

// Accounts
out.push('-- Accounts');
out.push(
  'insert into public.accounts (id, user_id, account_number, routing_number, type, name, balance, currency, status, opened_date, interest_rate) values'
);
const accountRows = accountsData.accounts.map(
  (a) =>
    `  (${uuid(a.id)}, ${uuid(a.userId)}, ${sqlString(a.accountNumber)}, ${sqlString(a.routingNumber)}, ${sqlString(a.type)}, ${sqlString(a.name)}, ${sqlNumber(a.balance)}, ${sqlString(a.currency)}, ${sqlString(a.status)}, ${sqlDate(a.openedDate)}, ${sqlNumber(a.interestRate)})`
);
out.push(accountRows.join(',\n') + '\non conflict (id) do nothing;\n');

// Cards (must come before transactions because txn.card_id -> cards.id)
out.push('-- Cards');
out.push(
  'insert into public.cards (id, user_id, account_id, card_number, last_four, type, network, name, status, expiry_date, cvv, credit_limit, balance, available_credit, rewards_points, issued_date, billing_cycle, next_payment_due, minimum_payment) values'
);
const cardRows = cardsData.cards.map(
  (c) =>
    `  (${uuid(c.id)}, ${uuid(c.userId)}, ${uuid(c.accountId)}, ${sqlString(c.cardNumber)}, ${sqlString(c.lastFour)}, ${sqlString(c.type)}, ${sqlString(c.network)}, ${sqlString(c.name)}, ${sqlString(c.status)}, ${sqlString(c.expiryDate)}, ${sqlString(c.cvv)}, ${sqlNumber(c.creditLimit)}, ${sqlNumber(c.balance)}, ${sqlNumber(c.availableCredit)}, ${sqlInteger(c.rewardsPoints)}, ${sqlDate(c.issuedDate)}, ${sqlInteger(c.billingCycle)}, ${sqlDate(c.nextPaymentDue)}, ${sqlNumber(c.minimumPayment)})`
);
out.push(cardRows.join(',\n') + '\non conflict (id) do nothing;\n');

// Transactions
out.push('-- Transactions');
out.push(
  'insert into public.transactions (id, user_id, account_id, card_id, type, category, merchant, description, amount, balance, date, status, location) values'
);
const txnRows = transactionsData.transactions.map(
  (t) =>
    `  (${uuid(t.id)}, ${uuid(t.userId)}, ${uuid(t.accountId)}, ${t.cardId ? uuid(t.cardId) : 'null'}, ${sqlString(t.type)}, ${sqlString(t.category)}, ${sqlString(t.merchant)}, ${sqlString(t.description)}, ${sqlNumber(t.amount)}, ${sqlNumber(t.balance)}, ${sqlTimestamp(t.date)}, ${sqlString(t.status)}, ${sqlString(t.location)})`
);
out.push(txnRows.join(',\n') + '\non conflict (id) do nothing;\n');

// Payees
out.push('-- Payees');
out.push(
  'insert into public.payees (id, user_id, name, account_number, category, default_amount, recurring_payment, last_payment) values'
);
const payeeRows = payeesData.payees.map(
  (p) =>
    `  (${uuid(p.id)}, ${uuid(p.userId)}, ${sqlString(p.name)}, ${sqlString(p.accountNumber)}, ${sqlString(p.category)}, ${sqlNumber(p.defaultAmount)}, ${sqlJson(p.recurringPayment)}, ${sqlJson(p.lastPayment)})`
);
out.push(payeeRows.join(',\n') + '\non conflict (id) do nothing;\n');

// Budgets + categories + savings goals
//
// Budgets aren't keyed by a legacy id in the JSON (they only have userId),
// so we derive a synthetic legacy id "BUD-<userId>" for each one so the
// uuid mapping stays deterministic.
out.push('-- Budgets');
out.push(
  'insert into public.budgets (id, user_id, monthly_budget) values'
);
const budgetRows = budgetsData.budgets.map(
  (b) =>
    `  (${uuid('BUD-' + b.userId)}, ${uuid(b.userId)}, ${sqlNumber(b.monthlyBudget)})`
);
out.push(budgetRows.join(',\n') + '\non conflict (user_id) do nothing;\n');

out.push('-- Budget categories');
const categoryRows = [];
for (const b of budgetsData.budgets) {
  b.categories.forEach((c, idx) => {
    const legacyId = `BCT-${b.userId}-${idx + 1}`;
    categoryRows.push(
      `  (${uuid(legacyId)}, ${uuid('BUD-' + b.userId)}, ${sqlString(c.name)}, ${sqlNumber(c.budget)}, ${sqlNumber(c.spent)}, ${sqlString(c.color)})`
    );
  });
}
if (categoryRows.length > 0) {
  out.push(
    'insert into public.budget_categories (id, budget_id, name, budget, spent, color) values'
  );
  out.push(categoryRows.join(',\n') + '\non conflict (id) do nothing;\n');
}

out.push('-- Savings goals');
const goalRows = [];
for (const b of budgetsData.budgets) {
  b.savingsGoals.forEach((g) => {
    goalRows.push(
      `  (${uuid(g.id)}, ${uuid('BUD-' + b.userId)}, ${sqlString(g.name)}, ${sqlNumber(g.target)}, ${sqlNumber(g.current)}, ${sqlString(g.color)})`
    );
  });
}
if (goalRows.length > 0) {
  out.push(
    'insert into public.savings_goals (id, budget_id, name, target, current, color) values'
  );
  out.push(goalRows.join(',\n') + '\non conflict (id) do nothing;\n');
}

out.push('commit;', '');

process.stdout.write(out.join('\n'));
